/*! \file volume_bar.h
 *  \brief Заголовочный файл с описанием класса VolumeBar
 *  \details Содержит объявление класса VolumeBar, представляющего полосу громкости.
 *           Класс наследует Bar и реализует интерфейс для управления визуальным представлением
 *           и функциональностью регулировки уровня громкости.
 */
#ifndef VOLUME_BAR
#define VOLUME_BAR
#include "bar.h"
#include <string>
#include "../Exceptions/exceptions.h"

/*! \class VolumeBar
 *  \brief Модель полосы громкости
 *  \details VolumeBar наследуется от Bar, предоставляя методы для управления
 *           длиной полосы и установки уровня громкости. Используется для визуального
 *           отображения и управления уровнем громкости аудиоплеера.
 */
class VolumeBar : public Bar
{
public:
    /*! \brief Конструктор по умолчанию
     *  \details Инициализирует полосу громкости с нулевой длиной.
     */
    VolumeBar();

    /*! \brief Деструктор
     *  \details Обеспечивает корректное уничтожение объекта полосы громкости.
     */
    ~VolumeBar();

    /*! \brief Явный конструктор с инициализацией длины
     *  \param length Длина полосы отображения
     *  \details Позволяет создать полосу громкости с заданной длиной визуального представления.
     */
    explicit VolumeBar(int length);

    /*! \brief Установить длину полосы
     *  \param length Новая длина полосы
     *  \details Устанавливает длину визуального представления полосы громкости.
     */
    void SetLength(int length) override;

    /*! \brief Получить длину полосы
     *  \return Длина полосы
     *  \details Возвращает текущую установленную длину полосы отображения.
     */
    int GetLength() const override;

    /*! \brief Установить уровень громкости
     *  \param volume Уровень громкости (0-100)
     *  \return Строка с информацией о результате установки громкости
     *  \details Устанавливает уровень громкости, проверяя корректность значения
     *           в пределах допустимого диапазона от 0 до 100.
     */
    std::string SetVolume(int volume);

private:
    int length_{0}; /*!< Длина визуального представления полосы громкости */
    static constexpr int minVolume{0}; /*!< Минимальный уровень громкости */
    static constexpr int maxVolume{100}; /*!< Максимальный уровень громкости */
};

#endif
