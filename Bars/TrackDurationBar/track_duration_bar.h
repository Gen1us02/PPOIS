/*! \file track_duration_bar.h
 *  \brief Заголовочный файл с описанием класса TrackDurationBar
 *  \details Содержит объявление класса TrackDurationBar, представляющего полосу длительности трека.
 *           Класс наследует Bar и реализует интерфейс для управления визуальным представлением
 *           и функциональностью перемотки длительности аудиотрека.
 */
#ifndef TRACK_DURATION_BAR
#define TRACK_DURATION_BAR
#include "bar.h"
#include <string>
#include "../Exceptions/exceptions.h"

/*! \class TrackDurationBar
 *  \brief Модель полосы длительности трека
 *  \details TrackDurationBar наследуется от Bar, предоставляя методы для управления
 *           длиной полосы, установки длительности трека и функциональности перемотки.
 *           Используется для визуального отображения и управления прогрессом воспроизведения трека.
 */
class TrackDurationBar : public Bar
{
public:
    /*! \brief Конструктор по умолчанию
     *  \details Инициализирует полосу длительности трека с нулевыми значениями длины и длительности.
     */
    TrackDurationBar();

    /*! \brief Деструктор
     *  \details Обеспечивает корректное уничтожение объекта полосы длительности трека.
     */
    ~TrackDurationBar();

    /*! \brief Конструктор с инициализацией длины и длительности
     *  \param length Длина полосы отображения
     *  \param duration Длительность трека в секундах
     *  \details Позволяет создать полосу длительности с заданными параметрами длины и длительности трека.
     */
    TrackDurationBar(int length, int duration);

    /*! \brief Установить длину полосы
     *  \param length Новая длина полосы
     *  \details Устанавливает длину визуального представления полосы прогресса.
     */
    void SetLength(int length) override;

    /*! \brief Получить длину полосы
     *  \return Длина полосы
     *  \details Возвращает текущую установленную длину полосы отображения.
     */
    int GetLength() const override;

    /*! \brief Установить длительность трека
     *  \param duration Длительность трека в секундах
     *  \details Устанавливает общую длительность трека для корректного отображения прогресса.
     */
    void SetDuration(int duration);

    /*! \brief Получить длительность трека
     *  \return Длительность трека в секундах
     *  \details Возвращает текущую установленную длительность трека.
     */
    int GetDuration() const;

    /*! \brief Перемотать длительность трека
     *  \param duration Новая позиция в секундах
     *  \return Строка с информацией о результате перемотки
     *  \details Устанавливает текущую позицию воспроизведения трека на указанное значение.
     *           Проверяет корректность запрашиваемой позиции в пределах длительности трека.
     */
    std::string RewindTrackDuration(int duration);

private:
    int length_{0}; /*!< Длина визуального представления полосы прогресса */
    int minDuration_{0}; /*!< Минимальная допустимая длительность трека в секундах */
    int maxDuration_{0}; /*!< Максимальная допустимая длительность трека в секундах */
};

#endif
