/*! \file button.h
*  \brief Заголовочный файл с описанием абстрактного класса Button
 *  \details Содержит объявление абстрактного класса Button, представляющего базовый интерфейс
 *           для различных типов кнопок в пользовательском интерфейсе.
 */
#ifndef BUTTON
#define BUTTON

/*! \class Button
 *  \brief Абстрактный базовый класс для кнопок различных типов
 *  \details Button определяет базовый интерфейс для всех видов кнопок, предоставляя методы
 *           для установки и получения ширины и высоты кнопки. Является родительским классом
 *           для специализированных типов кнопок.
 */
class Button
{
public:
    /*! \brief Виртуальный деструктор по умолчанию
     *  \details Обеспечивает корректное уничтожение объектов производных классов.
     */
    virtual ~Button() = default;

    /*! \brief Установить ширину кнопки
     *  \param width Новая ширина кнопки
     */
    virtual void SetWidth(int width) = 0;

    /*! \brief Получить ширину кнопки
     *  \return Ширина кнопки
     */
    virtual int GetWidth() const = 0;

    /*! \brief Установить высоту кнопки
     *  \param height Новая высота кнопки
     */
    virtual void SetHeight(int height) = 0;

    /*! \brief Получить высоту кнопки
     *  \return Высота кнопки
     */
    virtual int GetHeight() const = 0;
};

#endif
