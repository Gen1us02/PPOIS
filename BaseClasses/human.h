/*! \file human.h
*  \brief Заголовочный файл с описанием абстрактного класса Human
 *  \details Содержит объявление абстрактного класса Human, представляющего базовый интерфейс
 *           для классов, описывающих человека с основными персональными данными.
 */
#ifndef HUMAN
#define HUMAN

/*! \class Human
 *  \brief Абстрактный базовый класс для представления человека
 *  \details Human определяет базовый интерфейс для всех классов, представляющих человека,
 *           предоставляя методы для управления именем и возрастом. Является родительским
 *           классом для специализированных типов, описывающих людей в различных контекстах.
 */
class Human
{
public:
    /*! \brief Виртуальный деструктор по умолчанию
     *  \details Обеспечивает корректное уничтожение объектов производных классов.
     */
    virtual ~Human() = default;

    /*! \brief Установить имя человека
     *  \param name Новое имя человека
     */
    virtual void SetName(const std::string& name) = 0;

    /*! \brief Получить имя человека
     *  \return Строка с именем человека
     */
    virtual std::string GetName() const = 0;

    /*! \brief Установить возраст человека
     *  \param age Новый возраст человека
     */
    virtual void SetAge(int age) = 0;

    /*! \brief Получить возраст человека
     *  \return Возраст человека
     */
    virtual int GetAge() const = 0;
};

#endif
