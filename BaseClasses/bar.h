/*! \file bar.h
*  \brief Заголовочный файл с описанием абстрактного класса Bar
 *  \details Содержит объявление абстрактного класса Bar, представляющего базовый интерфейс
 *           для различных типов полос (прогресса, громкости, длительности и т.д.).
 */
#ifndef BAR
#define BAR

/*! \class Bar
 *  \brief Абстрактный базовый класс для полос различных типов
 *  \details Bar определяет базовый интерфейс для всех видов полос, предоставляя методы
 *           для установки и получения длины полосы. Является родительским классом для
 *           специализированных типов полос.
 */
class Bar
{
public:
    /*! \brief Виртуальный деструктор по умолчанию
     *  \details Обеспечивает корректное уничтожение объектов производных классов.
     */
    virtual ~Bar() = default;

    /*! \brief Установить длину полосы
     *  \param length Новая длина полосы
     */
    virtual void SetLength(int length) = 0;

    /*! \brief Получить длину полосы
     *  \return Длина полосы
     */
    virtual int GetLength() const = 0;
};

#endif
